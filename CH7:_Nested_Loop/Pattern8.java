//WAP to print start 5*5
public class Pattern8{
    public static void main(String[] args){
        int numofRows=5;
        for(int i=1; i<=numofRows; i++){
            for(int j=1; j<=5; j++){
                System.out.print("*");
            }
            System.out.println("");
        }
    }
}
     
